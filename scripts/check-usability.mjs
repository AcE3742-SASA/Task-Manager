// Fresh, isolated browser; synthetic localhost data only. Never run against a deployed app.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.DEMO_URL || 'http://127.0.0.1:5190'
assert.ok(/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base), 'local demo only')
const out = 'outputs/usability-implementation'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' })
const errors = [], external = []
page.on('pageerror', e => errors.push(e.message))
await page.route('**/*', route => {
  if (route.request().url().startsWith(base + '/')) return route.continue()
  external.push(route.request().url()); return route.abort()
})
const nav = path => page.locator(`.nav a[href="${path}"]`).click()
try {
  await page.goto(base)
  await page.waitForSelector('.task')
  assert.match(await page.title(), /\[DEV\]/)
  // Group collapse uses the existing main-branch behavior.
  const toggle = page.getByRole('button', { name: /^오늘 \d/ })
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
  await toggle.click()
  await nav('/new')
  assert.equal(await page.locator('.dock').count(), 0)
  await page.getByLabel('제목', { exact: true }).fill('초안과 기한 검증')
  await page.getByLabel('기한 (한국 시간)', { exact: true }).fill('2026-12-20T12:34')
  await page.getByLabel('메모 (선택)', { exact: true }).fill('화면 이동 후에도 남아야 하는 메모')
  await nav('/calendar')
  await nav('/new')
  assert.equal(await page.getByLabel('제목', { exact: true }).inputValue(), '초안과 기한 검증')
  assert.equal(await page.getByLabel('기한 (한국 시간)', { exact: true }).inputValue(), '2026-12-20T12:34')
  const save = page.getByRole('button', { name: '저장', exact: true })
  await save.scrollIntoViewIfNeeded()
  assert.equal(await save.evaluate(el => { const b=el.getBoundingClientRect(); return document.elementFromPoint(b.x+b.width/2,b.y+b.height/2)===el }), true)
  await page.screenshot({ path: `${out}/mobile-task-form.png` })
  await save.click()
  await page.waitForURL(base + '/')
  const row = page.locator('.task').filter({ hasText: '초안과 기한 검증' })
  await row.getByRole('button', { name: '기한 하루 늦추기', exact: true }).click()
  await page.getByRole('button', { name: '되돌리기', exact: true }).waitFor()
  assert.match(await page.locator('.action-notice').innerText(), /2026-12-21 12:34/)
  await page.getByRole('button', { name: '되돌리기', exact: true }).click()
  await page.getByText('기한을 원래대로 돌렸어요.', { exact: true }).waitFor()
  await page.getByRole('button', { name: '알림 닫기' }).click()
  await row.locator('.hit').click()
  assert.equal(await page.getByLabel('기한 (한국 시간)', { exact: true }).inputValue(), '2026-12-20T12:34')
  await nav('/new')
  await page.getByLabel('제목', { exact: true }).fill('날짜 없는 할 일')
  await page.getByRole('button', { name: '기한 없음', exact: true }).click()
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.waitForURL(base + '/')
  assert.equal(await page.locator('.task').filter({ hasText: '날짜 없는 할 일' }).locator('.snooze').count(), 0)

  await nav('/profile')
  const before = await page.evaluate(() => localStorage.getItem('sasa-demo-data-v1'))
  await page.locator('input[type=file]').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ app: 'sasa-task-manager', version: 1, subjects: [], tasks: [{ id: 'bad/path', title: {} }] })) })
  await page.getByText(/문서 ID가 올바르지 않아요/).waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('sasa-demo-data-v1')), before)
  const bundle = { app: 'sasa-task-manager', version: 1, exportedAt: new Date().toISOString(), settings: { lang: 'ko' }, subjects: [], tasks: [{ id: 'import-demo', title: '가져오기 검증', due: null }] }
  await page.locator('input[type=file]').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bundle)) })
  const replace = page.getByRole('button', { name: '이 파일의 내용으로 교체', exact: true })
  await replace.waitFor()
  assert.equal(await replace.isDisabled(), true)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '현재 데이터 백업 받기', exact: true }).click()
  await (await download).saveAs(`${out}/synthetic-before-import.json`)
  await page.getByLabel('백업 파일이 저장된 것을 확인했어요', { exact: true }).check()
  await replace.click()
  await page.getByText('과목 0개와 할 일 1건을 가져왔어요.', { exact: true }).waitFor()
  await nav('/')
  await page.getByRole('button', { name: /가져오기 검증/ }).waitFor()
  assert.equal(await page.locator('.task').count(), 1)

  // Empty first-use state in this isolated DEMO profile, without a real account.
  await page.evaluate(() => { localStorage.setItem('sasa-demo-data-v1', '{}'); sessionStorage.clear() })
  await page.reload()
  await page.getByRole('link', { name: /첫 할 일/ }).waitFor()
  await page.screenshot({ path: `${out}/mobile-first-use.png` })
  await page.goto(base + '/help')
  await page.waitForSelector('.guide')
  await page.screenshot({ path: `${out}/mobile-help.png` })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: `${out}/desktop-help.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, [])
  assert.deepEqual(external, [])
  console.log('PASS: collapse, draft restoration, unobstructed save, due time preservation+undo, undated action, invalid import zero writes, backup-gated atomic import, first-use CTA, mobile/desktop tutorial, no external requests')
} finally { await browser.close() }
